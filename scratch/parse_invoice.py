import csv, io
from collections import defaultdict

reader = csv.reader(io.StringIO(raw_csv.strip()))
rows = list(reader)

items = []
header_found = False
for r in rows:
    if len(r) > 1 and r[1] == 'SKU':
        header_found = True
        continue
    if header_found:
        if len(r) > 4 and r[1] and r[3] and r[3].strip().isdigit():
            sku = r[1].strip()
            size = r[2].strip()
            qty = int(r[3].strip())
            rate = float(r[4].strip())
            val = float(r[5].strip())
            gst_amt = float(r[7].strip()) if len(r) > 7 and r[7] else 0.0
            items.append({
                'sku': sku,
                'size': size,
                'qty': qty,
                'rate': rate,
                'value': val,
                'gst_amt': gst_amt
            })

print(f"Total line items parsed: {len(items)}")
total_qty = sum(x['qty'] for x in items)
total_val = sum(x['value'] for x in items)
total_gst = sum(x['gst_amt'] for x in items)
print(f"Total Quantity: {total_qty} pcs")
print(f"Total Base Value: Rs. {total_val:,.2f}")
print(f"Total GST (5%): Rs. {total_gst:,.2f}")
print(f"Total with GST: Rs. {total_val + total_gst:,.2f}")

# Group by SKU
sku_data = defaultdict(lambda: {'sizes': [], 'rate': 0, 'qty': 0, 'val': 0})
for it in items:
    s = it['sku']
    sku_data[s]['sizes'].append(f"{it['size']} ({it['qty']})")
    sku_data[s]['rate'] = it['rate']
    sku_data[s]['qty'] += it['qty']
    sku_data[s]['val'] += it['value']

print(f"\nUnique SKUs in this invoice ({len(sku_data)} total):")
for s, d in sku_data.items():
    print(f"  SKU: {s:15} | Rate: Rs. {d['rate']:6.0f} | Qty: {d['qty']:2} | Sizes: {', '.join(d['sizes'])}")
